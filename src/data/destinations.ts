import type { Destination, Region, TripStyle } from '../lib/types';

/**
 * Curated destination catalog.
 *
 * WHAT IS REAL: names, airports, city-centre coordinates, time zones.
 * WHAT IS ESTIMATED (and labeled as such in the UI):
 *   - costs: rough mid-range USD ranges (developer-curated, 2025–26 era), NOT live prices
 *   - experience ratings (1–5): editorial judgments
 *   - best/okay months: general climate knowledge; replaced by real Open-Meteo history when online
 *   - hyattCategories: approximate category spread of Hyatt hotels in the area — verify on hyatt.com
 *   - advisoryLevel: last-known US State Dept level, developer-seeded, may be outdated — always verify
 */

type Exp = Partial<Record<TripStyle, number>>;
type Prog = Destination['hotelPrograms'];

function D(
  id: string,
  name: string,
  country: string,
  region: Region,
  airports: string[],
  [lat, lon]: [number, number],
  utcOffset: number,
  experience: Exp,
  c: [number, number, number, number, number, number, number, number],
  bestMonths: number[],
  okayMonths: number[],
  opts: {
    hyatt?: [number, number];
    programs?: Prog;
    advisory?: 1 | 2 | 3 | 4 | null;
    slug?: string;
    wiki: string;
    blurb: string;
    domestic?: boolean;
  },
): Destination {
  return {
    id,
    name,
    country,
    region,
    domestic: opts.domestic ?? false,
    airports,
    lat,
    lon,
    utcOffset,
    experience,
    costs: { hotelNight: [c[0], c[1]], foodDay: [c[2], c[3]], localDay: [c[4], c[5]], activityDay: [c[6], c[7]] },
    bestMonths,
    okayMonths,
    hyattCategories: opts.hyatt,
    hotelPrograms: opts.programs ?? ['marriott', 'ihg'],
    advisoryLevel: opts.domestic ? null : (opts.advisory ?? null),
    advisorySlug: opts.slug,
    wikiTitle: opts.wiki,
    blurb: opts.blurb,
  };
}

